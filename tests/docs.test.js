const FIXTURE_DIRS = ["tests/fixtures", ...fs.readdirSync(path.join(root, "tracker/tests")).filter(d => d.startsWith("frames")).map(d => "tracker/tests/" + d)];
let fail = 0;
const bad = (doc, msg) => { fail++; console.log(`${doc}: ${msg}`) };

// a path with * matches if any file in its folder fits the pattern
const exists = rel => {
  if (!rel.includes("*")) return fs.existsSync(path.join(root, rel));
  const dir = path.join(root, path.dirname(rel)), re = new RegExp("^" + path.basename(rel).replace(/[.]/g, "\\.").replace(/\*/g, ".*") + "$");
  return fs.existsSync(dir) && fs.readdirSync(dir).some(f => re.test(f));
};
const found = p => BASES.some(b => exists(path.posix.join(b, p)));
const PATHY = /^(\.{0,2}\/)?[\w.*-]+(\/[\w.*-]+)*\/?$/, EXT = /\.(js|cjs|mjs|py|sh|md|json|yml|yaml|html|css|png|toml|txt)$/;
const scripts = new Set();
let checked = 0;
for (const pj of ["tracker/package.json", "server/package.json", "package.json"])
  if (fs.existsSync(path.join(root, pj))) Object.keys(JSON.parse(fs.readFileSync(path.join(root, pj), "utf8")).scripts || {}).forEach(s => scripts.add(s));

for (const doc of DOCS){
  const text = fs.readFileSync(path.join(root, doc), "utf8");
  const cands = new Set();
  for (const m of text.matchAll(/`([^`\n]+)`/g)) cands.add(m[1].trim());                 // inline code
  for (const m of text.matchAll(/^\| *([^|\n]+?) *\|/gm)) m[1].split(/,\s*/).forEach(c => cands.add(c));   // first table column (source maps)
  for (const m of text.matchAll(/\]\(([^)#\s]+)/g)) if (!/^\w+:/.test(m[1])) cands.add(path.posix.join(path.posix.dirname(doc), m[1]));   // md links, relative to the doc
  for (const m of text.matchAll(/```[^\n]*\n([\s\S]*?)```/g)) for (const line of m[1].split("\n")){   // commands in code blocks
    for (const c of line.split(/&&|;|\|/)){
      const run = c.match(/\b(?:python3|node)\s+(?:-\S+\s+)*([\w./-]+\.(?:py|js|cjs))/); if (run) cands.add(run[1]);
      const npm = c.match(/\bnpm run (\S+)/); if (npm && !scripts.has(npm[1])) bad(doc, `npm run ${npm[1]}: no such script`);
    }
  }
  for (const s of [...cands].flatMap(c => c.split(/\s+/))){
    const p = s.replace(/[,.:;)]+$/, "").replace(/^\.\//, "");
    if (/^\w+:/.test(p) || p.startsWith("/") || IGNORE.has(p) || !PATHY.test(p) || p.endsWith(".png")) continue;   // images: fixture check below
    if (!EXT.test(p) && !(p.endsWith("/") && p.length > 1)) continue;   // only things that look like files or folders
    checked++;
    if (!found(p.replace(/\/$/, ""))) bad(doc, `${p} not found`);
  }
}

// fixture index: every image listed, every listed image present
const idx = fs.readFileSync(path.join(root, "docs/ai/fixtures.md"), "utf8");
const listed = new Set([...idx.matchAll(/[\w.-]+\.png/g)].map(m => m[0]));
const images = FIXTURE_DIRS.flatMap(d => fs.readdirSync(path.join(root, d)).filter(f => f.endsWith(".png")));
for (const f of images) if (!listed.has(f)) bad("docs/ai/fixtures.md", `${f} has no row`);
for (const f of listed) if (!images.includes(f)) bad("docs/ai/fixtures.md", `${f} listed but not in the repo`);

if (fail){ console.log(`${fail} problem(s): fix the doc (or the IGNORE list in tests/docs.test.js)`); process.exit(1) }
console.log(`docs test passed (${DOCS.length} docs, ${checked} paths, ${images.length} fixtures)`);
