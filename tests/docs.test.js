const DOCS = ["CLAUDE.md", ...fs.readdirSync(path.join(root, "docs/ai")).filter(f => f.endsWith(".md")).map(f => "docs/ai/" + f)];
const BASES = ["", "src", "src/js", "tracker", "tracker/tests", "server", "data", "scripts", "docs", ".github/workflows"];
