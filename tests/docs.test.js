// 3. [CLAIM]/[RECLAIM]/[RELEASE] lines in agent-mailbox.md follow the lease format (mailbox § How to use).
// 4. Volatile docs carry a fresh `last-verified: YYYY-MM-DD by <agent>` stamp (VOLATILE list below).
