const {contextBridge, ipcRenderer} = require("electron");
contextBridge.exposeInMainWorld("host", {
  gameFound: () => ipcRenderer.invoke("game-found"),
  wholeScreen: on => ipcRenderer.invoke("whole-screen", on),
  settings: s => ipcRenderer.invoke("settings", s),
  saveSession: summary => ipcRenderer.invoke("save-session", summary),
  autosave: summary => ipcRenderer.invoke("autosave", summary),
  autosaveGet: () => ipcRenderer.invoke("autosave-get"),
  saveFrame: (name, bytes) => ipcRenderer.invoke("save-frame", name, bytes),
  saveImage: (name, bytes, quiet) => ipcRenderer.invoke("save-image", name, bytes, quiet),
  saveReport: (frames, info) => ipcRenderer.invoke("save-report", frames, info),
  openFolder: dir => ipcRenderer.invoke("open-folder", dir),
  ocr: png => ipcRenderer.invoke("ocr", png),
  shareRun: run => ipcRenderer.invoke("share-run", run),
  summary: () => ipcRenderer.invoke("summary"),
  sessions: () => ipcRenderer.invoke("sessions"),
  deleteSession: saved => ipcRenderer.invoke("delete-session", saved),
  updateSession: (saved, patch) => ipcRenderer.invoke("update-session", saved, patch),
  exportCsv: () => ipcRenderer.invoke("export-csv"),
  party: live => ipcRenderer.invoke("party", live),
  mini: (on, h) => ipcRenderer.invoke("mini", on, h),
  winSize: (w, h) => ipcRenderer.invoke("win-size", w, h),
  // overlay mode: a second, transparent window over the game (main.js owns it; this page builds the data for it)
  overlay: on => ipcRenderer.invoke("overlay", on),
  overlayEdit: () => ipcRenderer.invoke("ov-edit-toggle"),
  overlayPush: d => ipcRenderer.send("ov-push", d),
  onOverlay: cb => ipcRenderer.on("ov-state", (_, s) => cb(s)),
  menu: (label, x, y) => ipcRenderer.invoke("menu-popup", label, x, y),
  snip: url => ipcRenderer.invoke("snip", url),
  themeBar: c => ipcRenderer.invoke("theme-bar", c),
  keys: (keys, pause) => ipcRenderer.invoke("keys", keys, pause),
  version: () => ipcRenderer.invoke("version"),
  updateState: () => ipcRenderer.invoke("update-state"),
  updateCheck: () => ipcRenderer.invoke("update-check"),
  updateInstall: () => ipcRenderer.invoke("update-install"),
  onMenu: cb => ipcRenderer.on("menu", (_, what) => cb(what)),
  onUpdate: cb => ipcRenderer.on("update", (_, u) => cb(u)),
  onShare: cb => ipcRenderer.on("share", (_, s) => cb(s)),
});
